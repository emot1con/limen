CREATE TABLE IF NOT EXISTS fingerprint_subjects (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS fingerprint_templates (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id bigint NOT NULL REFERENCES fingerprint_subjects(id) ON DELETE CASCADE,
    template bytea NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_fingerprint_templates_subject
    ON fingerprint_templates(subject_id);

CREATE TABLE IF NOT EXISTS identifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_user_id uuid REFERENCES users(id) ON DELETE SET NULL,
    matched boolean NOT NULL,
    score double precision,
    candidate_count integer NOT NULL DEFAULT 0,
    fingerprint_id bigint,
    payload_json jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_identifications_created
    ON identifications(created_at);

CREATE INDEX IF NOT EXISTS idx_identifications_external_user
    ON identifications(external_user_id);
